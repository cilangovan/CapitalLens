#!/usr/bin/env python3
"""
Export the live database schema (and Supabase migration history) into git.

Writes:
  db/schema.sql                         full, ordered, re-runnable DDL for the public schema
                                        (extensions, roles, sequences, tables, keys, indexes, RLS, policies, comments,
                                        functions, triggers, views) — the baseline for a rollout or a move to another Postgres
  supabase/migrations/<version>_<name>.sql   exact SQL of every migration applied through Supabase (credential seeds redacted)

Connection (first one available wins):
  SUPABASE_DB_URL         postgres connection string → uses `psql` (portable; also what pg_dump uses)
  SUPABASE_ACCESS_TOKEN + SUPABASE_PROJECT_REF   Supabase Management API (no DB password needed)
  --from-json FILE        offline: render from a saved introspection result

Usage:
  python db/export_schema.py               # writes files, prints a summary
  python db/export_schema.py --check       # exit 1 if the committed files differ from the live DB (drift check)
"""

import argparse
import json
import os
import re
import subprocess
import sys
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCHEMA_FILE = ROOT / "db" / "schema.sql"
MIG_DIR = ROOT / "supabase" / "migrations"

# Extensions Supabase installs for itself — commented out in schema.sql so it runs on plain Postgres too
PLATFORM_EXTENSIONS = {"pg_stat_statements", "pgcrypto", "supabase_vault", "uuid-ossp", "pg_graphql", "pgsodium", "pgjwt"}

# Never write credentials into a (public) repo
REDACT = [
    (re.compile(r"insert\s+into\s+(public\.)?dashboard_auth\b.*?;", re.I | re.S),
     "-- [redacted] credential seed removed from version control — create your own login (see db/README.md)"),
    (re.compile(r"(--[^\n]*Seed initial user:)[^\n]*", re.I), r"\1 [redacted]"),
]

INTROSPECT_SQL = r"""
with t as (
  select c.oid, c.relname, c.relrowsecurity from pg_class c join pg_namespace n on n.oid=c.relnamespace
  where n.nspname='public' and c.relkind='r'
),
cols as (
  select t.relname, string_agg(
    format('  %I %s%s%s%s', a.attname, format_type(a.atttypid,a.atttypmod),
      case when a.attidentity='a' then ' generated always as identity' when a.attidentity='d' then ' generated by default as identity' else '' end,
      case when ad.adbin is not null and a.attidentity='' then ' default '||pg_get_expr(ad.adbin,ad.adrelid) else '' end,
      case when a.attnotnull then ' not null' else '' end), E',\n' order by a.attnum) cols
  from t join pg_attribute a on a.attrelid=t.oid and a.attnum>0 and not a.attisdropped
  left join pg_attrdef ad on ad.adrelid=t.oid and ad.adnum=a.attnum
  group by t.relname
),
cons as (
  select t.relname, string_agg(format(E',\n  constraint %I %s', co.conname, pg_get_constraintdef(co.oid)), '' order by co.contype desc, co.conname) cons
  from t join pg_constraint co on co.conrelid=t.oid where co.contype in ('p','u','c') group by t.relname
),
seq as (
  select s.relname seq, format_type(sq.seqtypid, null) typ, tt.relname tbl, a.attname col
  from pg_class s join pg_namespace n on n.oid=s.relnamespace join pg_sequence sq on sq.seqrelid=s.oid
  left join pg_depend d on d.objid=s.oid and d.deptype='a'
  left join pg_class tt on tt.oid=d.refobjid left join pg_attribute a on a.attrelid=tt.oid and a.attnum=d.refobjsubid
  where n.nspname='public' and s.relkind='S'
    and not exists (select 1 from pg_depend d2 where d2.objid=s.oid and d2.deptype='i')   -- identity columns own theirs
)
select json_build_object(
  'pg_version', current_setting('server_version'),
  'extensions', (select json_agg(json_build_object('name', e.extname, 'schema', n.nspname) order by e.extname)
                 from pg_extension e join pg_namespace n on n.oid=e.extnamespace where e.extname <> 'plpgsql'),
  'sequences', (select json_agg(json_build_object('name', seq, 'type', typ, 'table', tbl, 'column', col) order by seq) from seq),
  'tables', (select json_agg(json_build_object('name', t.relname,
               'ddl', format(E'create table if not exists public.%I (\n%s%s\n);', t.relname, cols.cols, coalesce(cons.cons,'')))
               order by t.relname) from t join cols using (relname) left join cons using (relname)),
  'foreign_keys', (select json_agg(format('alter table public.%I add constraint %I %s;', t.relname, co.conname, pg_get_constraintdef(co.oid))
               order by t.relname, co.conname) from t join pg_constraint co on co.conrelid=t.oid where co.contype='f'),
  'indexes', (select json_agg(pg_get_indexdef(i.indexrelid)||';' order by t.relname, ic.relname)
               from t join pg_index i on i.indrelid=t.oid join pg_class ic on ic.oid=i.indexrelid
               where not i.indisprimary and not exists (select 1 from pg_constraint co where co.conindid=i.indexrelid)),
  'rls', (select json_agg(relname order by relname) from t where relrowsecurity),
  'policies', (select json_agg(format('create policy %I on public.%I as %s for %s to %s%s%s;', p.policyname, p.tablename,
               lower(p.permissive), lower(p.cmd), array_to_string(p.roles, ', '),
               case when p.qual is not null then ' using ('||p.qual||')' else '' end,
               case when p.with_check is not null then ' with check ('||p.with_check||')' else '' end)
               order by p.tablename, p.policyname) from pg_policies p where p.schemaname='public'),
  'comments', (select json_agg(s order by s) from (
               select format('comment on column public.%I.%I is %L;', t.relname, a.attname, d.description) s
               from t join pg_description d on d.objoid=t.oid and d.objsubid>0 join pg_attribute a on a.attrelid=t.oid and a.attnum=d.objsubid
               union all select format('comment on table public.%I is %L;', t.relname, d.description)
               from t join pg_description d on d.objoid=t.oid and d.objsubid=0) x),
  'functions', (select json_agg(pg_get_functiondef(p.oid)||';' order by p.proname) from pg_proc p join pg_namespace n on n.oid=p.pronamespace
               where n.nspname='public' and not exists (select 1 from pg_depend d where d.objid=p.oid and d.deptype='e')),
  'triggers', (select json_agg(pg_get_triggerdef(tg.oid)||';' order by tg.tgname) from pg_trigger tg join t on t.oid=tg.tgrelid where not tg.tgisinternal),
  'views', (select json_agg(format(E'create or replace view public.%I%s as\n%s', c.relname,
               case when c.reloptions is not null then ' with ('||array_to_string(c.reloptions, ', ')||')' else '' end,
               rtrim(pg_get_viewdef(c.oid), ';')||';') order by c.relname)
               from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname='public' and c.relkind='v'),
  'function_acl', (select json_agg(json_build_object('sig', p.oid::regprocedure::text,
               'roles', (select json_agg(r) from unnest(array['anon','authenticated','service_role']) r
                         where has_function_privilege(r, p.oid, 'execute'))) order by p.proname)
               from pg_proc p join pg_namespace n on n.oid=p.pronamespace
               where n.nspname='public' and not exists (select 1 from pg_depend d where d.objid=p.oid and d.deptype='e')),
  'migrations', (select json_agg(json_build_object('version', version, 'name', name, 'sql', array_to_string(statements, E';\n')) order by version)
               from supabase_migrations.schema_migrations)
)::text
"""


# ── fetch ─────────────────────────────────────────────────────────────────────
def fetch_psql(db_url):
    out = subprocess.run(["psql", db_url, "-X", "-A", "-t", "-v", "ON_ERROR_STOP=1", "-c", INTROSPECT_SQL],
                         check=True, capture_output=True, text=True).stdout.strip()
    return json.loads(out)


def fetch_api(token, ref):
    req = urllib.request.Request(f"https://api.supabase.com/v1/projects/{ref}/database/query", method="POST",
                                 data=json.dumps({"query": INTROSPECT_SQL}).encode(),
                                 headers={"Authorization": f"Bearer {token}", "Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=60) as r:
        rows = json.loads(r.read())
    return json.loads(list(rows[0].values())[0])


# ── render ────────────────────────────────────────────────────────────────────
def section(title, lines):
    lines = [l for l in (lines or []) if l]
    return [f"\n-- ── {title} " + "─" * max(4, 70 - len(title)), *lines] if lines else []


def render_schema(d, source):
    exts = []
    for e in d.get("extensions") or []:
        stmt = f'create extension if not exists "{e["name"]}" with schema {e["schema"]};'
        exts.append(("-- (Supabase platform) " + stmt) if e["name"] in PLATFORM_EXTENSIONS else stmt)
    seqs = d.get("sequences") or []
    out = [
        "-- ═══════════════════════════════════════════════════════════════════════════",
        "-- T212 Monitor — database schema (public)",
        f"-- Generated by db/export_schema.py from the live database (Postgres {d.get('pg_version')}, via {source}).",
        "-- DO NOT EDIT BY HAND — change the DB with a migration, then re-run the export.",
        "-- Re-runnable on an empty Postgres 15+ database: psql \"$DATABASE_URL\" -f db/schema.sql",
        "-- Schema only — contains no data and no credentials.",
        "-- ═══════════════════════════════════════════════════════════════════════════",
        "",
        "begin;",
        "set local client_min_messages = warning;",
        "create schema if not exists extensions;",
        "set local search_path = public, extensions;",
    ]
    out += section("Extensions", exts)
    out += section("Roles (exist on Supabase; created here for plain Postgres)", [
        "do $$ begin",
        "  if not exists (select 1 from pg_roles where rolname = 'anon') then create role anon nologin; end if;",
        "  if not exists (select 1 from pg_roles where rolname = 'authenticated') then create role authenticated nologin; end if;",
        "  if not exists (select 1 from pg_roles where rolname = 'service_role') then create role service_role nologin bypassrls; end if;",
        "end $$;",
    ])
    out += section("Sequences", [f'create sequence if not exists public.{s["name"]} as {s["type"]};' for s in seqs])
    out += section("Tables", ["\n\n".join(t["ddl"] for t in d.get("tables") or [])])
    out += section("Sequence ownership", [f'alter sequence public.{s["name"]} owned by public.{s["table"]}.{s["column"]};'
                                          for s in seqs if s.get("table")])
    out += section("Foreign keys", [re.sub(r"^alter table (\S+) add constraint (\S+) ",
                                           r"alter table \1 drop constraint if exists \2;\nalter table \1 add constraint \2 ", fk)
                                    for fk in d.get("foreign_keys") or []])
    out += section("Indexes", [re.sub(r"^CREATE (UNIQUE )?INDEX ", lambda m: f"CREATE {m.group(1) or ''}INDEX IF NOT EXISTS ", i)
                               for i in d.get("indexes") or []])
    out += section("Row level security", [f"alter table public.{t} enable row level security;" for t in d.get("rls") or []])
    pols = d.get("policies") or []
    out += section("Policies (anon = dashboard reads; writes only via service role)",
                   [re.sub(r'^create policy ("[^"]+"|\S+) on (\S+) ', r"drop policy if exists \1 on \2;\ncreate policy \1 on \2 ", p) for p in pols])
    out += section("Grants (Supabase default: API roles can reach public tables; RLS decides rows)", [
        "grant usage on schema public to anon, authenticated, service_role;",
        "grant select on all tables in schema public to anon, authenticated;",
        "grant all on all tables in schema public to service_role;",
        "grant usage, select on all sequences in schema public to service_role;",
    ])
    out += section("Comments", d.get("comments"))
    out += section("Functions", d.get("functions"))
    out += section("Triggers", d.get("triggers"))
    out += section("Views", d.get("views"))
    acl = []
    for f in d.get("function_acl") or []:
        sig = re.sub(r"^(public\.)?", "public.", f["sig"])
        acl.append(f"revoke all on function {sig} from public, anon, authenticated;")
        acl += [f"grant execute on function {sig} to {r};" for r in (f.get("roles") or [])]
    out += section("Function privileges", acl)
    out += ["", "commit;", ""]
    return "\n".join(out)


def redact(sql):
    for pat, rep in REDACT:
        sql = pat.sub(rep, sql)
    return sql


def migration_files(d):
    files = {}
    for m in d.get("migrations") or []:
        name = re.sub(r"[^a-z0-9_]+", "_", m["name"].lower()).strip("_")
        body = redact(m["sql"].strip())
        files[MIG_DIR / f'{m["version"]}_{name}.sql'] = (
            f'-- Supabase migration {m["version"]} "{m["name"]}" — exported from supabase_migrations.schema_migrations\n'
            f"{body}\n")
    return files


# ── main ──────────────────────────────────────────────────────────────────────
def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--from-json")
    ap.add_argument("--check", action="store_true", help="exit 1 if files would change")
    a = ap.parse_args()

    if a.from_json:
        d, source = json.loads(Path(a.from_json).read_text()), "saved introspection"
    elif os.environ.get("SUPABASE_DB_URL"):
        d, source = fetch_psql(os.environ["SUPABASE_DB_URL"]), "psql"
    elif os.environ.get("SUPABASE_ACCESS_TOKEN") and os.environ.get("SUPABASE_PROJECT_REF"):
        d, source = fetch_api(os.environ["SUPABASE_ACCESS_TOKEN"], os.environ["SUPABASE_PROJECT_REF"]), "Supabase Management API"
    else:
        sys.exit("No connection: set SUPABASE_DB_URL, or SUPABASE_ACCESS_TOKEN + SUPABASE_PROJECT_REF (see db/README.md)")

    outputs = {SCHEMA_FILE: render_schema(d, source), **migration_files(d)}
    changed = [p for p, txt in outputs.items() if not p.exists() or p.read_text() != txt]
    if a.check:
        for p in changed: print(f"drift: {p.relative_to(ROOT)}")
        sys.exit(1 if changed else 0)
    MIG_DIR.mkdir(parents=True, exist_ok=True)
    for p, txt in outputs.items():
        p.write_text(txt)
    print(f"[export] {len(d.get('tables') or [])} tables, {len(d.get('policies') or [])} policies, "
          f"{len(d.get('migrations') or [])} migrations — {len(changed)} file(s) changed "
          f"({datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC)")
    for p in changed: print(f"  • {p.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
